export function findSampleSet(name) {
  const wanted = String(name || FIXED_20.name).trim();
  const set = SAMPLE_SETS.find(candidate => candidate.name === wanted);
  if (!set) throw new Error(`알 수 없는 샘플 세트: ${wanted} (사용 가능: ${SAMPLE_SETS.map(item => item.name).join(', ')})`);
  return set;
}
